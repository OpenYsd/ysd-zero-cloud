/**
 * Regenerates `db/migrations/0001_auth.sql` from Better Auth itself.
 *
 * D1 has no local CLI connection Better Auth can introspect, so the schema is
 * compiled here against an empty in-memory SQLite database and committed. Both
 * targets use the same Kysely SQLite dialect, so the emitted DDL is what D1
 * receives.
 *
 * Run after upgrading Better Auth or changing `lib/server/auth-options.ts`:
 *
 *   npm run auth:schema
 */
import { DatabaseSync } from 'node:sqlite';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { getMigrations } from 'better-auth/db/migration';

import { buildAuthOptions, DEVELOPMENT_AUTH_SECRET } from '../lib/server/auth-options.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'db', 'migrations', '0001_auth.sql');

const database = new DatabaseSync(':memory:');

const options = buildAuthOptions({
  database,
  secret: DEVELOPMENT_AUTH_SECRET,
  // Include GitHub so the account table carries every column the provider
  // needs; the runtime only enables the provider when credentials exist.
  github: { clientId: 'schema-generation', clientSecret: 'schema-generation' },
});

const { compileMigrations, toBeCreated } = await getMigrations(options);
const sql = await compileMigrations();

const header = [
  '-- Better Auth schema for YSD Zero Cloud.',
  '--',
  '-- Generated by `npm run auth:schema`. Do not edit by hand: rerun the script',
  '-- after changing lib/server/auth-options.ts or upgrading better-auth.',
  `-- Tables: ${toBeCreated.map((table) => table.table).join(', ')}`,
  '',
].join('\n');

await mkdir(dirname(target), { recursive: true });
await writeFile(target, `${header}${sql.trim()}\n`, 'utf8');

database.close();

console.log(`Wrote ${toBeCreated.length} table(s) to db/migrations/0001_auth.sql`);
